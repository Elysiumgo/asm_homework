.MODEL SMALL
.STACK 100H
.DATA
LETTER DB 'a'
ROW_COUNT DB 0
COL_COUNT DB 0
.CODE
START:
    MOV AX,@DATA
    MOV DS,AX

ROW_START:
    MOV COL_COUNT,0
COL_START:
    MOV DL,LETTER
    MOV AH,02H
    INT 21H
    INC LETTER
    INC COL_COUNT
    CMP COL_COUNT,13
    JAE ROW_END

    MOV DL,' '
    MOV AH,02H
    INT 21H
    JMP COL_START

ROW_END:
    MOV DL,0DH
    MOV AH,02H
    INT 21H
    MOV DL,0AH
    MOV AH,02H
    INT 21H

    INC ROW_COUNT
    CMP ROW_COUNT,2
    JB ROW_START

    MOV AX,4C00H
    INT 21H
END START
