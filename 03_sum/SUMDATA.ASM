.MODEL SMALL
.STACK 100H
.DATA
RESULT DW 0               ; the sum is stored in the data segment
NUMBER DW 1
.CODE
START:
    MOV AX,@DATA
    MOV DS,AX

SUM_LOOP:
    MOV AX,RESULT
    ADD AX,NUMBER
    MOV RESULT,AX
    INC NUMBER
    CMP NUMBER,100
    JBE SUM_LOOP

    MOV AX,RESULT
    CALL PRINT_NUM
    CALL NEW_LINE
    MOV AX,4C00H
    INT 21H

PRINT_NUM PROC NEAR
    PUSH BX
    PUSH CX
    PUSH DX
    XOR CX,CX
    MOV BX,10
DIVIDE:
    XOR DX,DX
    DIV BX
    PUSH DX
    INC CX
    OR AX,AX
    JNZ DIVIDE
PRINT_DIGIT:
    POP DX
    ADD DL,'0'
    MOV AH,02H
    INT 21H
    LOOP PRINT_DIGIT
    POP DX
    POP CX
    POP BX
    RET
PRINT_NUM ENDP

NEW_LINE PROC NEAR
    MOV DL,0DH
    MOV AH,02H
    INT 21H
    MOV DL,0AH
    MOV AH,02H
    INT 21H
    RET
NEW_LINE ENDP
END START
